package com.acme.notes.data

import io.ktor.client.HttpClient
import io.ktor.client.call.body
import io.ktor.client.request.get
import kotlinx.serialization.Serializable

@Serializable
data class Note(
    val id: String,
    val title: String,
)

/**
 * Plain Ktor call, no Either and no Result wrapper — this is a pre-KMPilot
 * codebase, so the compatibility report should list the missing pieces.
 */
class NotesApi(
    private val client: HttpClient,
) {
    suspend fun notes(): List<Note> = client.get("https://api.example.com/notes").body()
}
EOF

