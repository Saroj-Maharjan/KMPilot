#!/usr/bin/env bash
# Generate the scratch KMP target used to test `install.sh --adopt`.
#
# The fixture is a deliberately ORDINARY Kotlin Multiplatform app: Compose
# Multiplatform, Koin and Ktor, its own version catalog, its own package prefix,
# and no KMPilot anything. Adopt-mode must work on a repo it has never seen.
#
# It is generated rather than committed so the test is repeatable and the
# fixture never drifts into the template's shape by accident. Only this script
# lives in the repo (scripts/ is stripped by install.sh and is not delivered by
# update.sh, so it stays upstream-only).
#
# Usage:
#   scripts/make-adopt-target.sh [target-dir] [--force]
#
#   target-dir  default: ~/KMPProjects/adopt-target
#   --force     regenerate over an existing fixture (only ever deletes a
#               directory carrying the .adopt-target-fixture marker)
#
# Deliberate differences from KMPilot, each one exercising a detection path:
#   • module names        app/ + shared/         (not androidApp/ + composeApp/)
#   • rootProject.name    AcmeNotes              (drives the generated-resources package)
#   • package prefix      com.acme.notes         (three segments, not one)
#   • version catalog     its own alias naming   (kmpilotLibs must not collide)
#   • root build.gradle   no allprojects{} conventions at all — vendored core
#                         modules must configure their own compileSdk/minSdk
#   • targets             android + ios only     (no desktop in the app module)
#
# Not generated: an iosApp Xcode project. Adopt-mode never writes into one, and
# the phase's exit criteria are `assembleDebug` + `archTest`, both Android/JVM.

set -euo pipefail

TARGET="${HOME}/KMPProjects/adopt-target"
FORCE=no
for arg in "$@"; do
    case "$arg" in
        --force) FORCE=yes ;;
        -h|--help) sed -n '2,30p' "$0"; exit 0 ;;
        -*) echo "Error: unknown argument '$arg'" >&2; exit 1 ;;
        *)  TARGET="$arg" ;;
    esac
done

NAME="AcmeNotes"
PKG="com.acme.notes"
PKG_PATH="${PKG//.//}"
MARKER=".adopt-target-fixture"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KMPILOT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

command -v git >/dev/null 2>&1 || { echo "Error: git is required" >&2; exit 1; }

if [[ -e "$TARGET" ]]; then
    if [[ "$FORCE" != "yes" ]]; then
        echo "Error: '$TARGET' already exists. Pass --force to regenerate it." >&2
        exit 1
    fi
    # Only ever delete something this script created.
    if [[ ! -f "$TARGET/$MARKER" ]]; then
        echo "Error: '$TARGET' exists but has no $MARKER marker — refusing to delete it." >&2
        exit 1
    fi
    echo "→ Removing existing fixture at $TARGET"
    rm -rf "$TARGET"
fi

echo "→ Generating $NAME fixture at $TARGET"
mkdir -p "$TARGET"
cd "$TARGET"

mkdir -p "app/src/main/kotlin/${PKG_PATH}/android"
mkdir -p "shared/src/commonMain/kotlin/${PKG_PATH}"/{data,di,notes}
mkdir -p "shared/src/androidMain/kotlin/${PKG_PATH}"
mkdir -p "shared/src/iosMain/kotlin/${PKG_PATH}"
mkdir -p gradle/wrapper

cat > "$MARKER" <<'EOF'
Generated by KMPilot's scripts/make-adopt-target.sh — a disposable test fixture
for `install.sh --adopt`. Safe to delete. Regenerate with --force.
EOF

